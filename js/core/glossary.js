/** หาคำอธิบายจากคีย์ */
export function explain(key) {
  return GLOSSARY[key] || null;
}

/** รายการคำศัพท์ทั้งหมด เรียงตามชื่อไทย ใช้ทำหน้าพจนานุกรม */
export function allTerms() {
  return Object.entries(GLOSSARY)
    .map(([key, value]) => ({ key, ...value }))
    .sort((a, b) => a.termTh.localeCompare(b.termTh, 'th'));
}

/** ค้นหาคำศัพท์ */
export function searchTerms(query) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return allTerms();
  return allTerms().filter(t =>
    t.termTh.toLowerCase().includes(q)
    || (t.aliasTh || '').toLowerCase().includes(q)
    || t.whatTh.toLowerCase().includes(q)
    || t.domainTh.toLowerCase().includes(q)
  );
}
