/**
 * ประกอบข้อเท็จจริงจากผลคำนวณ ให้อยู่ในรูปที่ AI เอาไปเล่าต่อได้
 * @param {object} analysis ผลจาก LifeDomainsEngine.analyze
 * @param {object} profile โปรไฟล์ผู้ใช้
 */
export function buildFactSheet(analysis, profile = {}) {
  if (!analysis || !analysis.available) {
    return { available: false, reasonTh: analysis?.reasonTh || 'ยังไม่มีข้อมูลดวงที่คำนวณไว้' };
  }

  const meta = analysis.meta || {};
  const bazi = meta.bazi || {};
  const taksa = meta.taksa || {};
  const thai = meta.thai || {};
  const zodiac = meta.zodiac || {};
  const chong = meta.chong || {};
  const luck = meta.currentLuck || {};
  const scores = meta.scores || {};
  const stage = lifeStageOf(meta.age);

  const known = [];
  known.push('[ข้อเท็จจริงจากการคำนวณ ใช้ได้เฉพาะข้อมูลในกรอบนี้]');

  if (meta.age != null) known.push('อายุ: ' + meta.age + ' ปี');
  if (taksa.birthDayTh) known.push('เกิดวัน: ' + taksa.birthDayTh);
  if (zodiac.nameTh) known.push('ปีนักษัตร: ปี' + zodiac.nameTh);

  // ต้องแยกให้ชัดว่าธาตุสองตัวนี้คนละเรื่อง เพราะโมเดลเคยสับสนแล้วพูดผิด
  if (bazi.dayMasterElement?.nameTh) {
    known.push('ธาตุประจำตัวจากดวงจีน: ธาตุ' + bazi.dayMasterElement.nameTh
      + ' (ตัวนี้คือธาตุของตัวเขาเอง ใช้บอกนิสัยและแนวทางชีวิต)');
  }
  if (thai.bodyElement?.nameTh) {
    known.push('ธาตุเจ้าเรือนจากโหราศาสตร์ไทย: ' + thai.bodyElement.nameTh
      + ' (คนละตัวกับธาตุประจำตัว ใช้เรื่องการดูแลร่างกาย ห้ามเอาไปสลับกัน)');
  }
  if (bazi.strength?.labelTh) known.push('กำลังธาตุประจำตัว: ' + bazi.strength.labelTh);
  if (bazi.strength?.plainTh) known.push('แปลว่า: ' + bazi.strength.plainTh);

  if (luck.nameTh) {
    known.push('รอบโชคชะตาสิบปีที่กำลังอยู่: '
      + (luck.isFavourable ? 'เป็นรอบที่หนุนดวง' : 'เป็นรอบที่ยังไม่หนุน'));
  }
  if (chong.headlineTh) known.push('เรื่องปีชง: ' + chong.headlineTh);
  if (bazi.missingElementsTh?.length) {
    known.push('ธาตุที่ขาดในดวง: ' + bazi.missingElementsTh.join(' และ '));
  }

  // ดาวที่มีจริงในดวง ต้องระบุให้ครบ เพราะโมเดลเคยแต่งดาวที่ไม่มีขึ้นมาเอง
  const godsTh = meta.godsTh || (analysis.domains?.career?.godsTh);
  if (Array.isArray(godsTh) && godsTh.length) {
    known.push('ดาวที่ปรากฏในดวงมีเท่านี้ ห้ามอ้างดาวอื่นนอกรายการนี้: ' + godsTh.join(', '));
  }

  // คะแนนใช้ภายในเท่านั้น ห้ามให้โมเดลพูดตัวเลขออกไป จึงแปลงเป็นคำก่อนส่ง
  const domainNames = { career: 'การงาน', money: 'การเงิน', love: 'ความรัก', health: 'สุขภาพ', luck: 'โชคลาภ' };
  const levelOf = (n) => (n >= 78 ? 'เด่นมาก' : n >= 68 ? 'ค่อนข้างดี' : n >= 58 ? 'กลาง ๆ' : n >= 48 ? 'ต้องออกแรงหน่อย' : 'เป็นจุดที่ต้องระวัง');

  Object.entries(domainNames).forEach(([key, nameTh]) => {
    const s = scores[key];
    if (!s) return;
    const top = (s.factors || []).slice().sort((a, b) => Math.abs(b.points) - Math.abs(a.points))[0];
    known.push('ด้าน' + nameTh + ': ' + levelOf(s.score)
      + (top ? ' เพราะ' + top.reasonTh : ''));
  });

  // จุดที่ดวงขัดกันเอง คือจุดที่ทำให้คำทำนายรู้สึกจริง เพราะคนจริงก็ขัดกันเอง
  const tensions = [];
  if (scores.career && scores.money && Math.abs(scores.career.score - scores.money.score) >= 12) {
    tensions.push(scores.career.score > scores.money.score
      ? 'เรื่องงานไปได้ดีกว่าเรื่องเก็บเงิน'
      : 'หาเงินได้ดีกว่าที่ตำแหน่งงานจะบอก');
  }
  if (scores.love && scores.career && scores.love.score - scores.career.score >= 15) {
    tensions.push('เรื่องคนรอบตัวและความรักไปได้ดีกว่าเรื่องงาน');
  }
  if (bazi.strength && bazi.strength.isStrong === false && scores.career?.score >= 68) {
    tensions.push('ดูเป็นคนที่ต้องพึ่งทีม แต่ผลงานที่ออกมากลับดี');
  }
  if (bazi.strength?.isStrong && scores.love?.score < 58) {
    tensions.push('ยืนด้วยตัวเองได้ดี แต่เรื่องความสัมพันธ์กลับไม่ง่าย');
  }
  if (tensions.length) {
    known.push('จุดที่ดวงขัดกันเอง (ใช้เล่าให้คนอ่านรู้สึกว่าตรง): ' + tensions.join(' / '));
  }

  // สิ่งที่ระบบไม่รู้ ต้องบอกให้ชัด ไม่งั้นโมเดลจะเดาแล้วพูดเหมือนรู้จริง
  const unknown = [];
  unknown.push('[สิ่งที่ระบบไม่รู้ ห้ามพูดเหมือนรู้ ให้ใช้คำว่า ถ้า หรือ ตั้งคำถามกลับ]');
  if (!meta.hasTime) unknown.push('ไม่ทราบเวลาเกิด จึงดูลัคนาและภพไม่ได้ ห้ามพูดถึงลัคนาหรือภพ');
  unknown.push('ไม่รู้ว่าตอนนี้โสดหรือมีคู่');
  unknown.push('ไม่รู้ว่าทำงานอะไร เป็นลูกจ้างหรือเจ้าของกิจการ');
  unknown.push('ไม่รู้ว่ามีหนี้ มีรถ มีบ้าน หรือมีลูกหรือไม่');
  unknown.push('ไม่รู้ว่าเรียนจบอะไร อยู่จังหวัดไหน');

  if (stage) {
    unknown.push('เรื่องที่คนวัย ' + meta.age + ' ปีมักเจอ (เป็นสถิติทั่วไป ไม่ใช่เรื่องของเขา '
      + 'ให้ยกมาแบบตั้งคำถามว่าใช่ไหม): ' + stage.concernsTh.join(', '));
  }

  return {
    available: true,
    stage,
    hasTime: Boolean(meta.hasTime),
    factsTh: known.join(NL),
    unknownTh: unknown.join(NL),
    tensions
  };
}

