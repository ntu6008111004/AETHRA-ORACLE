  'พลังงานไหลเวียน', 'วงจรชีวิต', 'ความอุดมสมบูรณ์', 'จักรวาลส่งสัญญาณ',
  'ชีวิตแห้ง', 'เปิดรับสิ่งใหม่', 'ปล่อยวาง', 'เชื่อมั่นในตัวเอง',
  'ทุกอย่างจะดีขึ้น', 'ขอให้โชคดี', 'รักษาสมดุลพลังงาน', 'พลังงานด้านการปรับตัว',
  'ความละเอียดอ่อน', 'ขยายโอกาส', 'เปิดใจรับฟัง', 'จัดลำดับความสำคัญ',
  'ดูแลการพักผ่อนให้เพียงพอ', 'ทบทวนเป้าหมาย'
