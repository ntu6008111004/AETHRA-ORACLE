export class ChineseZodiacEngine {
  /** หาปีนักษัตรจากวันเกิด โดยยึดลี่ชุนเป็นเส้นแบ่งที่ถูกต้อง */
  static getZodiac(birthDateStr, birthTimeStr = '12:00', tzOffsetHours = 7) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(String(birthDateStr || ''))) {
      throw new TypeError('ปีนักษัตรต้องใช้วันเกิดในรูปแบบ YYYY-MM-DD');
    }
    const [y, m, d] = birthDateStr.split('-').map(Number);
    const hasTime = /^\d{1,2}:\d{2}$/.test(String(birthTimeStr || ''));
    const [hh, mm] = (hasTime ? birthTimeStr : '12:00').split(':').map(Number);
    const utc = new Date(Date.UTC(y, m - 1, d, hh - tzOffsetHours, mm));

    const zodiacYear = getBaZiYear(utc);
    const branchIndex = ((zodiacYear - 4) % 12 + 12) % 12;
    const branch = EARTHLY_BRANCHES[branchIndex];
    const bornBeforeLiChun = zodiacYear !== y;

    return {
      zodiacYear,
      buddhistYear: zodiacYear + 543,
      branchIndex,
      branch,
      nameTh: branch.nameTh,
      animalTh: branch.animalTh,
      animalEn: branch.animalEn,
      elementTh: branch.elementTh,
      profile: ZODIAC_PROFILES[branchIndex],
      bornBeforeLiChun,
      noteTh: bornBeforeLiChun
        ? 'คุณเกิดก่อนวันลี่ชุนของปีนั้น ตามหลักโหราศาสตร์จีนจึงนับเป็นปี' + branch.nameTh
          + ' (ค.ศ. ' + zodiacYear + ') ไม่ใช่ปีนักษัตรของปีเกิดตามปฏิทินสากล จุดนี้เว็บดูดวงหลายแห่งคำนวณผิด'
        : 'คุณเกิดหลังวันลี่ชุนของปีนั้น จึงนับเป็นปี' + branch.nameTh + ' ตรงตามปีเกิดปกติ'
    };
  }

  /**
   * หาว่าในปีที่กำหนด นักษัตรใดชงบ้าง
   * @param {number} targetYear ปี ค.ศ. ที่ต้องการตรวจ
   */
  static getClashYears(targetYear = new Date().getFullYear()) {
    const yearBranchIndex = ((targetYear - 4) % 12 + 12) % 12;
    const pick = (offset) => EARTHLY_BRANCHES[(yearBranchIndex + offset) % 12];

    return {
      targetYear,
      buddhistYear: targetYear + 543,
      yearBranch: EARTHLY_BRANCHES[yearBranchIndex],
      direct: {
        branch: pick(6),
        labelTh: 'ชงตรง (ปะทะเต็ม 100%)',
        plainTh: 'เป็นนักษัตรที่ปะทะกับปีนี้ตรง ๆ ตำราจีนแนะนำให้ระวังเรื่องสุขภาพ การเดินทาง และการตัดสินใจเรื่องใหญ่'
      },
      kak: {
        branch: pick(0),
        labelTh: 'คัก (ชงตัวเอง)',
        plainTh: 'ปีนักษัตรเดียวกับปีนี้ เรียกว่าชงตัวเอง มักเจอเรื่องเปลี่ยนแปลงในชีวิต เช่น ย้ายงาน ย้ายบ้าน'
      },
      heng: {
        branch: pick(9),
        labelTh: 'เฮ้ง (ชงร่วม)',
        plainTh: 'ได้รับผลกระทบรองลงมา มักเป็นเรื่องคนรอบตัวและความสัมพันธ์'
      },
      pua: {
        branch: pick(3),
        labelTh: 'ผั่ว (ชงร่วม)',
        plainTh: 'ได้รับผลกระทบรองลงมา มักเป็นเรื่องการเงินและข้อตกลงที่อาจเปลี่ยนแปลง'
      },
      remedies: CHONG_REMEDIES
    };
  }

  /** ตรวจว่าคนคนนี้ชงในปีที่กำหนดหรือไม่ พร้อมคำอธิบายที่ใช้ได้จริง */
  static checkChong(birthDateStr, birthTimeStr = '12:00', targetYear = new Date().getFullYear(), tzOffsetHours = 7) {
    const me = this.getZodiac(birthDateStr, birthTimeStr, tzOffsetHours);
    const clash = this.getClashYears(targetYear);

    const matched = ['direct', 'kak', 'heng', 'pua']
      .filter(key => clash[key].branch.index === me.branchIndex)
      .map(key => ({ type: key, ...clash[key] }));

    const isChong = matched.length > 0;
    const beYear = targetYear + 543;

    return {
      zodiac: me,
      targetYear,
      buddhistYear: beYear,
      yearBranchTh: clash.yearBranch.nameTh,
      isChong,
      matched,
      headlineTh: isChong
        ? 'ปี พ.ศ. ' + beYear + ' คุณ (ปี' + me.nameTh + ') เข้าข่าย "' + matched[0].labelTh + '"'
        : 'ปี พ.ศ. ' + beYear + ' คุณ (ปี' + me.nameTh + ') ไม่ชง ถือว่าเป็นปีที่เดินได้ตามปกติ',
      adviceTh: isChong
        ? matched[0].plainTh + ' คำแนะนำคือ อย่าเพิ่งลงทุนก้อนใหญ่แบบไม่ศึกษา อย่าค้ำประกันให้ใคร ขับรถให้ระวังขึ้น และตรวจสุขภาพประจำปีให้ครบ ส่วนการแก้ชงเป็นเรื่องของความสบายใจ ทำแล้วใจนิ่งขึ้นก็ถือว่าได้ผลแล้ว'
        : 'ปีนี้ไม่มีแรงปะทะจากปีนักษัตร เป็นจังหวะที่เหมาะกับการวางแผนระยะยาว เริ่มสิ่งใหม่ หรือขยับขยายงาน',
      allClashes: clash
    };
  }
}
