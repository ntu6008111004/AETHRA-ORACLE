export class ThaiAstrologyEngine {
  /** ธาตุเจ้าเรือนจากเดือนเกิด ตามตำราแพทย์แผนไทย */
  static getBodyElement(birthDateStr) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(String(birthDateStr || ''))) {
      throw new TypeError('ธาตุเจ้าเรือนต้องใช้วันเกิดในรูปแบบ YYYY-MM-DD');
    }
    const month = Number(birthDateStr.split('-')[1]);
    const found = Object.values(THAI_BODY_ELEMENTS).find(el => el.months.includes(month));
    return found || THAI_BODY_ELEMENTS.fire;
  }

  /**
   * ผังภพ 12 — เริ่มจากลัคนา
   * ถ้าไม่ทราบเวลาเกิดจะไม่มีลัคนา จึงคืน null พร้อมเหตุผล (ไม่เดา)
   */
  static calculateHouses(birthDateStr, birthTimeStr, lat, lon) {
    const chart = AstrologyEngine.calculateChart(birthDateStr, birthTimeStr, lat, lon);
    const ascendant = chart.western.ascendant;

    if (!ascendant) {
      return {
        available: false,
        reasonTh: 'คำนวณภพ 12 ไม่ได้เพราะไม่ทราบเวลาเกิดที่แน่นอนหรือไม่ทราบสถานที่เกิด — ภพทั้ง 12 ต้องเริ่มนับจากลัคนา ซึ่งเปลี่ยนทุก ๆ 2 ชั่วโมง ระบบจึงไม่เดาให้',
        houses: null,
        chart
      };
    }

    const ascIndex = ZODIAC_SIGNS.findIndex(s => s.id === ascendant.id);
    const houses = THAI_HOUSES.map((house, i) => {
      const sign = ZODIAC_SIGNS[(ascIndex + i) % 12];
      return {
        ...house,
        sign,
        signNameTh: sign.nameTh,
        rulerTh: THAI_SIGN_RULERS[sign.id].rulerTh,
        signTraitTh: THAI_SIGN_RULERS[sign.id].traitTh
      };
    });

    return {
      available: true,
      ascendant,
      ascendantNameTh: ascendant.nameTh,
      houses,
      byNumber: Object.fromEntries(houses.map(h => [h.number, h])),
      chart
    };
  }

  /** สรุปโหราศาสตร์ไทยทั้งชุด */
  static analyze(profile) {
    const { birthDate, birthTime, lat, lon } = profile;
    const bodyElement = this.getBodyElement(birthDate);
    const houseChart = this.calculateHouses(birthDate, birthTime, lat, lon);
    const chart = houseChart.chart;

    // ราศีเกิดแบบไทย (นิรายนะ) — หักค่าอายนางศะออกจากตำแหน่งสายนะ
    const thaiSun = chart.thai.suriyayartSun;

    return {
      bodyElement,
      thaiSunSign: thaiSun,
      thaiSunSignNameTh: thaiSun.nameTh,
      thaiSunRulerTh: THAI_SIGN_RULERS[thaiSun.id].rulerTh,
      westernSunSign: chart.western.sun,
      signDiffersNoteTh: thaiSun.id !== chart.western.sun.id
        ? 'ราศีเกิดแบบไทย (' + thaiSun.nameTh + ') ต่างจากราศีแบบสากล (' + chart.western.sun.nameTh
          + ') เพราะโหราศาสตร์ไทยใช้ระบบนิรายนะ ซึ่งหักค่าการเคลื่อนของจุดวสันตวิษุวัตออกราว 24 องศา ทั้งสองค่าถูกต้องทั้งคู่ เพียงแต่คนละระบบ'
        : 'ราศีเกิดแบบไทยและแบบสากลตรงกันพอดีในกรณีของคุณ',
      houses: houseChart,
      chart
    };
  }
}
