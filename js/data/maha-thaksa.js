/** คำนวณเลขนำโชคจากกำลังวันเกิด ตามที่ตำราระบุ */
export function luckyNumbersFromPower(planetId) {
  const entry = PLANET_POWER[planetId];
  if (!entry) return null;

  const power = entry.power;
  // เลขสองหลักที่บวกกันได้เท่ากำลังวัน ตามวิธีที่ตำรานิยมใช้
  const pairs = [];
  for (let a = 0; a <= 9; a++) {
    for (let b = 0; b <= 9; b++) {
      if (a + b === power) pairs.push(String(a) + String(b));
    }
  }

  return {
    planetTh: entry.planetTh,
    dayTh: entry.dayTh,
    power,
    digitTh: entry.numberTh,
    pairsSummingToPower: pairs,
    explainTh: 'กำลังของ' + entry.planetTh + 'คือ ' + power
      + ' ตามคัมภีร์มหาทักษา จึงถือเลข ' + power + ' เป็นเลขประจำตัว'
      + (pairs.length
        ? ' และเลขสองหลักที่บวกกันได้ ' + power + ' คือ ' + pairs.join(' ')
        : ' แต่ไม่มีเลขสองหลักที่บวกกันได้ ' + power + ' เพราะเกิน 18')
  };
}
