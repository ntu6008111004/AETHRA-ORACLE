export function lifeStageOf(age) {
  // ต้องกันค่าว่างให้ชัด เพราะ Number(null) และ Number('') ได้ 0
  // ซึ่งจะทำให้ระบบเดาว่าคนที่ไม่รู้อายุเป็นวัยเรียน กลายเป็นการเดาแทนผู้ใช้
  if (age === null || age === undefined || age === '' || typeof age === 'boolean') return null;
  const n = Number(age);
  if (!Number.isFinite(n) || n < 0) return null;
  return LIFE_STAGES.find(s => n >= s.minAge && n <= s.maxAge) || null;
}

